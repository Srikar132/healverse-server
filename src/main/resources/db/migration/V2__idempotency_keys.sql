-- Remembers the response of a write request that carried an Idempotency-Key header, so a retry
-- of the same request (e.g. the mobile app replaying its offline queue) returns the original
-- result instead of creating a duplicate.
CREATE TABLE idempotency_keys (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL,
    idempotency_key character varying(64) NOT NULL,
    response_json text NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT uk_idempotency_user_key UNIQUE (user_id, idempotency_key)
);
