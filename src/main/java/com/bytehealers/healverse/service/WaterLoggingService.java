package com.bytehealers.healverse.service;

import com.bytehealers.healverse.exception.*;
import com.bytehealers.healverse.dto.request.LogWaterRequest;
import com.bytehealers.healverse.dto.request.QuickWaterLogRequest;
import com.bytehealers.healverse.dto.request.UpdateWaterLogRequest;
import com.bytehealers.healverse.model.User;
import com.bytehealers.healverse.model.WaterLog;
import com.bytehealers.healverse.repo.UserRepository;
import com.bytehealers.healverse.repo.WaterLogRepository;
import lombok.extern.slf4j.Slf4j;
import lombok.RequiredArgsConstructor;
import org.springframework.stereotype.Service;

import java.math.BigDecimal;
import java.time.Clock;
import java.time.LocalDate;
import java.time.LocalDateTime;
import java.util.List;
import java.util.Optional;

@Service
@Slf4j
@RequiredArgsConstructor
public class WaterLoggingService {

    private final WaterLogRepository waterLogRepository;

    private final NutritionSyncService nutritionSyncService;

    private final UserRepository userRepository;

    private final Clock clock;

    private final UserTime userTime;

    public WaterLog logWater(LogWaterRequest request, Long userId) {
        User user = getUserOrThrow(userId); // 🔥 Fetch the user

        WaterLog waterLog = new WaterLog(
                null, // ID (autogenerated)
                user,
                request.getAmountMl(),
                request.getLoggedAt() != null ? request.getLoggedAt() : LocalDateTime.now(clock),
                null // createdAt (set by @PrePersist)
        );

        WaterLog savedLog = waterLogRepository.save(waterLog);

        syncNutritionSummary(userId, savedLog.getLoggedAt());

        return savedLog;
    }

    public WaterLog logQuickWater(QuickWaterLogRequest request, Long userId) {
        User user = getUserOrThrow(userId);

        BigDecimal amount = new BigDecimal(request.getPreset().getMilliliters());

        WaterLog waterLog = new WaterLog(
                null,
                user,
                amount,
                request.getLoggedAt() != null ? request.getLoggedAt() : LocalDateTime.now(clock),
                null
        );

        WaterLog savedLog = waterLogRepository.save(waterLog);

        syncNutritionSummary(userId, savedLog.getLoggedAt());

        return savedLog;
    }

    // The nutrition-summary sync is a side-effect, not the point of this
    // request — a failure in it (e.g. AI diet-plan generation erroring) must
    // never turn a successful log into an error response.
    private void syncNutritionSummary(Long userId, LocalDateTime loggedAt) {
        try {
            nutritionSyncService.syncAfterWaterLog(userId, loggedAt);
        } catch (Exception e) {
            log.warn("Nutrition summary sync failed after water log for userId {}: {}", userId, e.getMessage());
        }
    }

    public List<WaterLog> getTodaysWaterLogs(Long userId) {
        return getWaterLogsByDate(userId, userTime.today(userId));
    }

    public List<WaterLog> getWaterLogsByDate(Long userId, LocalDate date) {
        UserTime.DayRange day = userTime.dayRange(userId, date);
        return waterLogRepository.findByUserIdAndLoggedAtBetween(userId, day.start(), day.endInclusive());
    }

    public BigDecimal getTotalWaterIntakeToday(Long userId) {
        return getTodaysWaterLogs(userId).stream()
                .map(WaterLog::getAmountMl)
                .reduce(BigDecimal.ZERO, BigDecimal::add);
    }

    public List<WaterLog> getWaterLogsByDateRange(Long userId, LocalDate startDate, LocalDate endDate) {
        UserTime.DayRange range = userTime.range(userId, startDate, endDate);
        return waterLogRepository.findByUserIdAndLoggedAtBetween(userId, range.start(), range.endInclusive());
    }

    public WaterLog updateWaterLog(Long waterLogId, UpdateWaterLogRequest request, Long userId) {
        // Owner-scoped lookup: another user's log is indistinguishable from a missing one
        WaterLog waterLog = waterLogRepository.findByIdAndUser_Id(waterLogId, userId)
                .orElseThrow(() -> new ResourceNotFoundException("Water log not found"));

        waterLog.setAmountMl(request.getAmountMl());

        WaterLog savedLog = waterLogRepository.save(waterLog);

        syncNutritionSummary(userId, savedLog.getLoggedAt());

        return savedLog;
    }

    public boolean deleteWaterLog(Long waterLogId, Long userId) {
        // Owner-scoped lookup: another user's log is indistinguishable from a missing one
        Optional<WaterLog> existingLog = waterLogRepository.findByIdAndUser_Id(waterLogId, userId);

        if (existingLog.isEmpty()) {
            return false;
        }

        WaterLog waterLog = existingLog.get();

        LocalDateTime loggedAt = waterLog.getLoggedAt();
        waterLogRepository.delete(waterLog);

        syncNutritionSummary(userId, loggedAt);

        return true;
    }


    private User getUserOrThrow(Long userId) {
        return userRepository.findById(userId)
                .orElseThrow(() -> new ResourceNotFoundException("User not found"));
    }
}
